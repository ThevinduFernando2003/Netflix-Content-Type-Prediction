"""Write ``reports/data_profile.md`` from the raw catalogue."""

from __future__ import annotations

import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

import pandas as pd
from src.config import repo_root, resolve_path
from src.data.clean import clean_catalogue
from src.data.load import load_raw_csv
from src.logging_conf import configure_logging


def _markdown_table(frame: pd.DataFrame) -> str:
    headers = [str(column) for column in frame.columns]
    lines = [
        "| " + " | ".join(headers) + " |",
        "| " + " | ".join("---" for _ in headers) + " |",
    ]
    for row in frame.itertuples(index=False):
        cells = [str(value).replace("|", "\\|") for value in row]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def build_profile(raw: pd.DataFrame, cleaned: pd.DataFrame) -> str:
    """Return the profile markdown for ``raw`` and its cleaned form."""
    synthesized = list(raw.attrs.get("synthesized_columns", []))
    source_columns = [column for column in raw.columns if column not in synthesized]
    n_rows = len(raw)
    empty_counts = []
    for column in raw.columns:
        empty = int((raw[column].astype(str).str.strip() == "").sum())
        empty_counts.append(
            {
                "column": column,
                "dtype_on_load": "string",
                "empty_count": empty,
                "empty_pct": round(100.0 * empty / n_rows, 2),
            }
        )
    empty_table = _markdown_table(pd.DataFrame(empty_counts))

    class_counts = raw["type"].value_counts()
    class_rows = [
        {
            "type": label,
            "count": int(class_counts[label]),
            "pct": round(100.0 * int(class_counts[label]) / n_rows, 2),
        }
        for label in class_counts.index
    ]

    rating_counts = raw["rating"].replace("", "(blank)").value_counts()
    rating_rows = [{"rating": label, "count": int(count)} for label, count in rating_counts.items()]

    genres: Counter[str] = Counter()
    for value in raw["listed_in"].tolist():
        for part in str(value).split(","):
            token = part.strip()
            if token:
                genres[token] += 1
    genre_rows = [{"genre": genre, "count": count} for genre, count in genres.most_common()]

    year_counts = (
        pd.to_numeric(raw["release_year"], errors="coerce")
        .dropna()
        .astype(int)
        .value_counts()
        .sort_index()
    )
    year_rows = [
        {"release_year": int(year), "count": int(count)} for year, count in year_counts.items()
    ]

    duplicate_ids = int(raw["show_id"].duplicated().sum())
    synthesized = cleaned.attrs.get("synthesized_columns", [])
    lines = [
        "# Data profile",
        "",
        "Generated by `scripts/profile_data.py` from `data/raw/netflix_titles.csv`.",
        "Empty strings are the missingness this extract uses. Pandas dtypes are all string",
        "because the loader refuses type inference (titles such as `3%` and `23:59` must stay text).",
        "",
        f"- Rows: **{n_rows}**",
        f"- Columns in the source file: **{len(source_columns)}** ({', '.join(source_columns)})",
        f"- Duplicate `show_id` values: **{duplicate_ids}**",
        f"- Columns synthesized because the source omitted them: **{synthesized or 'none'}**",
        f"- Rating values moved into `duration`: **{cleaned.attrs.get('rating_shifts', 0)}**",
        f"- `date_added` parse failures: **{cleaned.attrs.get('date_parse_failures', 0)}**",
        f"- `duration` parse failures (non-empty but neither minutes nor seasons): "
        f"**{cleaned.attrs.get('duration_parse_failures', 0)}**",
        "",
        "## Class balance of `type`",
        "",
        _markdown_table(pd.DataFrame(class_rows)),
        "",
        "## Empty counts",
        "",
        "An empty string after stripping is counted as missing. The source Excel uses the",
        "placeholder `Not Given` for director and country; those are reported in the raw",
        "rating/country tables below and normalised to empty by `clean_catalogue`.",
        "",
        empty_table,
        "",
        "## `rating` value counts (raw, before the duration-shift repair)",
        "",
        _markdown_table(pd.DataFrame(rating_rows)),
        "",
        "## `listed_in` genre vocabulary",
        "",
        _markdown_table(pd.DataFrame(genre_rows)),
        "",
        "## `release_year` distribution",
        "",
        _markdown_table(pd.DataFrame(year_rows)),
        "",
        "## Parse notes",
        "",
        "`date_added` is parsed only with explicit formats `%m/%d/%Y`, `%B %d, %Y`, and `%b %d, %Y`.",
        "This extract stores dates as `M/D/YYYY` (the Excel source had mixed strings and datetime cells).",
        "`duration` accepts `90 min` and `2 Seasons`. Anything else is a parse failure.",
        "",
    ]
    return "\n".join(lines)


def main() -> None:
    configure_logging()
    raw = load_raw_csv()
    cleaned = clean_catalogue(raw)
    report = build_profile(raw, cleaned)
    destination = resolve_path("reports/data_profile.md")
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(report, encoding="utf-8")
    print(f"Wrote {destination.relative_to(repo_root())}")


if __name__ == "__main__":
    main()
