logger = get_logger(__name__)

METRIC_ORDER = [
    "accuracy",
    "balanced_accuracy",
    "precision_movie",
    "recall_movie",
    "f1_movie",
    "precision_tv",
    "recall_tv",
    "f1_tv",
    "f1_macro",
    "roc_auc",
    "average_precision",
]


def banned_feature_list() -> list[str]:
    """Columns and genre names the honest model must not see."""
    config = get_config()
    banned = list(config["leakage"]["banned_columns"])
    if not bool(config["features"].get("use_has_director", False)):
        banned.append("has_director")
    banned.extend(config["leakage"]["banned_tv_genres"])
    return banned


def assert_honest_inputs(spec: FeatureSpec) -> None:
    """Fail training if a banned column was added to the honest feature spec."""
    banned = set(get_config()["leakage"]["banned_columns"])
    if not bool(get_config()["features"].get("use_has_director", False)):
        banned.add("has_director")
    overlap = sorted(set(spec.all_columns) & banned)
    if overlap:
        raise RuntimeError(
            "Honest feature spec contains banned columns: "
            + ", ".join(overlap)
            + ". See reports/leakage_audit.md."
        )


def assert_feature_names(names: list[str]) -> None:
    """Fail if a fitted transformer emitted a duration or listed_in feature."""
    for name in names:
        lowered = name.casefold()
        if "duration" in lowered or "listed_in" in lowered:
            raise RuntimeError(f"Banned feature reintroduced into the fitted pipeline: {name}")
        if (
            not bool(get_config()["features"].get("use_has_director", False))
            and "has_director" in lowered
        ):
            raise RuntimeError(f"has_director was banned and reappeared as {name}")


def comparison_markdown(reports: list[CandidateReport]) -> str:
    """Sortable CV table. Mean ± std on the training folds only."""
    header = "| model | best params | " + " | ".join(METRIC_ORDER) + " | fit time (s) | notes |"
    rule = "| " + " | ".join("---" for _ in range(3 + len(METRIC_ORDER) + 1)) + " |"
    lines = [
        "# Model comparison",
        "",
        "Generated by `src/models/train.py` via 5-fold stratified CV on the 85% training split.",
        "The primary selection metric is ROC-AUC. Accuracy is shown because the dummy makes the floor obvious.",
        "Movie is the negative class and TV Show is the positive class.",
        "",
        header,
        rule,
    ]
    ranked = sorted(reports, key=lambda report: report.metrics["roc_auc"][0], reverse=True)
    for report in ranked:
        cells = [report.name, _params(report.best_params)]
        for metric in METRIC_ORDER:
            mean, std = report.metrics[metric]
            cells.append(f"{mean:.4f} ± {std:.4f}")
        cells.append(f"{report.fit_time_mean:.2f}")
        cells.append("; ".join(report.notes) if report.notes else "")
        lines.append("| " + " | ".join(cells) + " |")
    lines.extend(
        [
            "",
            "ComplementNB sees title TF-IDF and one-hot categoricals only.",
            "Tree models reduce the TF-IDF block with TruncatedSVD inside each fold.",
            "A linear model within 0.005 ROC-AUC of the leader is preferred so the API can show token contributions.",
            "",
        ]
    )
    return "\n".join(lines)


def _params(params: dict[str, Any]) -> str:
    if not params:
        return "(defaults)"
    return ", ".join(f"{key}={value}" for key, value in sorted(params.items()))


def _refit_variant(
    report: CandidateReport, spec: FeatureSpec, x: pd.DataFrame, y: pd.Series
) -> Any:
    candidate = ModelCandidate(
        name=report.name,
        estimator=clone(report.pipeline.named_steps["clf"]),
        drop_numeric=report.drop_numeric,
        svd_components=report.svd_components,
        densify=report.densify,
    )
    pipeline = make_pipeline(spec, candidate)
    pipeline.fit(x, y)
    return pipeline


def _feature_names(pipeline: Any) -> list[str]:
    names = pipeline.named_steps["preprocess"].get_feature_names_out()
    return [str(name) for name in names]


def run_training(
    *,
    candidates: list[ModelCandidate] | None = None,
    n_iter: int | None = None,
    reports_path: Any = None,
    source: pd.DataFrame | None = None,
    artifact_dir: Any = None,
    strict_auc: bool = True,
) -> dict[str, Any]:
    """Fit every candidate, calibrate the winner, and write artifacts."""
    from pathlib import Path

    from src.config import resolve_path

    if source is None:
        raw = load_raw_csv()
        data_hash = file_sha256(raw_csv_path())
    else:
        raw = source
        data_hash = "provided-frame"
    cleaned = clean_catalogue(raw)
    split = stratified_split(cleaned)
    y_train = encode_label(split.y_train)
    spec = honest_spec(cleaned)
    assert_honest_inputs(spec)
    x_train = prepare_features(split.x_train, spec)

    reports = [
        evaluate_candidate(spec, candidate, x_train, y_train, n_iter=n_iter)
        for candidate in (candidates or default_candidates())
    ]
    winner = select_winner(reports)
    winner_auc = winner.metrics["roc_auc"][0]
    if strict_auc and winner_auc >= 0.999:
        raise RuntimeError(
            f"Honest CV ROC-AUC is {winner_auc:.4f}. That is a leak. "
            "Read reports/leakage_audit.md before serving this model."
        )

    names = _feature_names(winner.pipeline)
    assert_feature_names(names)
    logger.info("Winner %s CV ROC-AUC %.4f", winner.name, winner_auc)

    raw_oof, calibrated_oof = out_of_fold_probabilities(winner.pipeline, x_train, y_train)
    threshold_info = tune_threshold(y_train, calibrated_oof)
    calibrator = fit_calibrator(winner.pipeline, x_train, y_train)

    leaky = leaky_spec(cleaned)
    x_leaky = prepare_features(split.x_train, leaky)
    leaky_model = _refit_variant(winner, leaky, x_leaky, y_train)

    ablated_spec = no_tv_vocabulary_spec(cleaned)
    assert_honest_inputs(ablated_spec)
    x_ablated = prepare_features(split.x_train, ablated_spec)
    ablated_model = _refit_variant(winner, ablated_spec, x_ablated, y_train)

    config = get_config()
    audit_path = resolve_path("reports/leakage_audit.md")
    metadata: dict[str, Any] = {
        "model_name": winner.name,
        "model_version": "1.0.0",
        "trained_at": utc_now(),
        "git_sha": git_sha(),
        "data_sha256": data_hash,
        "row_count": int(len(cleaned)),
        "train_rows": int(len(x_train)),
        "test_rows": int(len(split.x_test)),
        "library_versions": library_versions(),
        "cv_scores": {
            report.name: {
                "best_params": report.best_params,
                "metrics": {
                    key: {"mean": mean, "std": std} for key, (mean, std) in report.metrics.items()
                },
                "fit_time_mean": report.fit_time_mean,
            }
            for report in reports
        },
        "winner_cv_roc_auc": winner_auc,
        "test_scores": None,
        "threshold": threshold_info["threshold"],
        "threshold_f1_macro": threshold_info["f1_macro"],
        "high_precision_threshold": threshold_info["high_precision_threshold"],
        "threshold_rule": (
            "Maximise F1-macro on out-of-fold isotonic-calibrated P(TV Show). "
            "The 15% test set is not used."
        ),
        "oof_brier_raw": float(np.mean((raw_oof - y_train.to_numpy()) ** 2)),
        "oof_brier_calibrated": float(np.mean((calibrated_oof - y_train.to_numpy()) ** 2)),
        "feature_columns": list(spec.all_columns),
        "feature_names": names,
        "banned_features": banned_feature_list(),
        "positive_class": "TV Show",
        "label_map": {"Movie": 0, "TV Show": 1},
        "confidence_margins": {
            "high": float(config["threshold"]["high_margin"]),
            "medium": float(config["threshold"]["medium_margin"]),
        },
        "spec": {
            "text": list(spec.text_columns),
            "categorical": list(spec.categorical_columns),
            "numeric": list(spec.numeric_columns),
            "extra_categorical": list(spec.extra_categorical),
            "strip_tv_vocabulary": spec.strip_tv_vocabulary,
        },
        "use_rating": bool(config["features"].get("use_rating", False)),
        "use_has_director": bool(config["features"].get("use_has_director", False)),
        "description_in_model": "description" in spec.text_columns,
        "synthesized_columns": list(cleaned.attrs.get("synthesized_columns", [])),
        "leakage_audit_md": audit_path.read_text(encoding="utf-8") if audit_path.exists() else "",
        "served_model": "calibrator.joblib",
        "explanation_model": "best_model.joblib",
    }
    save_artifacts(
        best_model=winner.pipeline,
        calibrator=calibrator,
        label_encoder={"Movie": 0, "TV Show": 1},
        metadata=metadata,
        extra_models={
            "leaky_model.joblib": leaky_model,
            "no_tv_model.joblib": ablated_model,
        },
        directory=None if artifact_dir is None else Path(artifact_dir),
    )
    model_folder = (
        Path(artifact_dir)
        if artifact_dir is not None
        else resolve_path(config["paths"]["model_dir"])
    )
    np.savez(
        model_folder / "oof_probabilities.npz",
        y=y_train.to_numpy(),
        raw=raw_oof,
        calibrated=calibrated_oof,
    )
    report_path = (
        Path(reports_path)
        if reports_path
        else resolve_path(config["paths"]["reports_dir"]) / "model_comparison.md"
    )
    report_path.parent.mkdir(parents=True, exist_ok=True)
    report_path.write_text(comparison_markdown(reports), encoding="utf-8")
    logger.info("Wrote %s", report_path)
    return metadata
